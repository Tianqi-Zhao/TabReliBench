"""Export benchmark scalars and training meta-features to portable TSV tables.

Only load pickle files generated by a trusted benchmark execution.
"""
import argparse
from pathlib import Path
import pickle
import re

import numpy as np
import pandas as pd

BASE = {'realmlp', 'realmlp_hpo', 'xgboost_quantile', 'xgboost_quantile_hpo', 'bart'}


def aggregate_trials(trials):
    keys = ['task', 'dataset_id', 'model', 'ensemble', 'metric']
    if trials.duplicated(keys + ['seed']).any():
        raise ValueError('Duplicate dataset/model/ensemble/seed/metric records')
    return trials.groupby(keys, dropna=False, as_index=False).agg(
        mean_across_five_splits=('value', 'mean'), n_seeds=('value', 'count'))


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--results', type=Path, required=True, help='Root containing task/metrics directories')
    p.add_argument('--features', type=Path, help='Root containing task/dataset_<id>_seed_<s>.pkl')
    p.add_argument('--training-scales', type=Path, help='TSV from paper_analysis.training_scales')
    p.add_argument('--ensemble', type=int, default=8, help='Ensemble size of this execution root')
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args()
    rows = []
    for task in ('classification', 'regression'):
        for path in sorted((args.results/task/'metrics').glob('*_metrics.pkl')):
            with path.open('rb') as f:
                record = pickle.load(f)
            if record['task'] != task or float(record['ratio']) != 1:
                raise ValueError(f'Unexpected task or ratio: {path}')
            if int(record['seed']) not in range(5):
                raise ValueError(f'Expected seeds 0–4: {path}')
            base = {k: record[k] for k in ('task', 'dataset_id', 'model', 'seed')}
            base['ensemble'] = 0 if record['model'] in BASE else args.ensemble
            stored = record.get('model_metadata', {}).get('n_estimators', record.get('n_estimators'))
            if record['model'] not in BASE and stored is not None and int(stored) != args.ensemble:
                raise ValueError(f'Ensemble mismatch: {path}')
            slots = [('alpha_free.per_dataset.', record['alpha_free']['per_dataset'])]
            slots += [(f'alpha_dependent.{float(a)}.per_dataset.', s['per_dataset'])
                      for a, s in record['alpha_dependent'].items()]
            for prefix, values in slots:
                for metric, value in values.items():
                    if isinstance(value, (float, int, np.number)):
                        rows.append(dict(base, metric=prefix+metric, value=float(value)))
    if not rows:
        raise ValueError('No benchmark metrics found')
    trials = pd.DataFrame(rows)
    if args.training_scales:
        scales = pd.read_csv(args.training_scales, sep='\t')
        crps = trials[trials.metric.eq('alpha_free.per_dataset.crps_mean')].merge(
            scales, on=['task', 'dataset_id', 'seed'], how='left', validate='many_to_one')
        if not (np.isfinite(crps.training_response_std) & crps.training_response_std.ge(0)).all():
            raise ValueError('Missing or invalid training-response scales')
        crps['value'] /= crps.training_response_std.clip(lower=1e-10)
        crps['metric'] = 'alpha_free.per_dataset.crps_normalized'
        trials = pd.concat([trials, crps[trials.columns]], ignore_index=True)
    args.output.mkdir(parents=True, exist_ok=True)
    aggregate_trials(trials).to_csv(args.output/'dataset_metrics.tsv', sep='\t', index=False)
    trials.to_csv(args.output/'trial_metrics.tsv', sep='\t', index=False)
    if args.features:
        rows = []
        for task in ('classification', 'regression'):
            for path in sorted((args.features/task).glob('dataset_*_seed_*.pkl')):
                match = re.fullmatch(r'dataset_(\d+)_seed_(\d+)\.pkl', path.name)
                did, seed = map(int, match.groups())
                if seed not in range(5):
                    raise ValueError(f'Expected seeds 0–4: {path}')
                with path.open('rb') as f:
                    values = pickle.load(f)
                for feature, value in values.items():
                    if isinstance(value, (float, int, np.number)):
                        rows.append(dict(task=task, dataset_id=did, seed=seed, feature=feature, value=value))
        if not rows:
            raise ValueError('No feature cache files found')
        features = pd.DataFrame(rows)
        keys = ['task', 'dataset_id', 'feature']
        if features.duplicated(keys+['seed']).any():
            raise ValueError('Duplicate feature records')
        features.groupby(keys, as_index=False).agg(mean_across_five_splits=('value', 'mean'),
            n_seeds=('value', 'count')).to_csv(args.output/'dataset_feature_means.tsv', sep='\t', index=False)


if __name__ == '__main__':
    main()
